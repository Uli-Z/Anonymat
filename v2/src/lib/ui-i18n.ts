export function translateDiagnostic(language:Language,message:string):string{
  if(language==='de')return message;
  // Diagnostics originate in the language-neutral detection engine. Only their
  // rendered presentation is translated; the original text is left untouched.
  let text=translate(language,message);
  if(text!==message)return text;
  const patterns:[RegExp,string][]=[
    [/^Datum "([^"]+)": (.*?) – bitte manuell prüfen\.$/, 'Date "$1": $2 – please review manually.'],
    [/^Unvollständiges Datum "([^"]+)" mit Wochentag wird nicht verschoben; bitte als Token prüfen\.$/, 'Incomplete date "$1" with weekday was not shifted; review as a token.'],
    [/^"([^"]+)" enthält keinen bestimmten Kalendertag und wird als Token ersetzt\.$/, '"$1" has no specific calendar day and was replaced with a token.'],
    [/^Datum "([^"]+)" konnte nicht sicher verschoben werden; stattdessen als Token ersetzt\.$/, 'Date "$1" could not be safely shifted and was replaced with a token.'],
    [/^Für "([^"]+)" war kein eindeutiges Pseudonym verfügbar; stattdessen Platzhalter verwendet\.$/, 'No unique pseudonym was available for "$1"; a placeholder was used.'],
    [/^Ersatzwert für (.*?) ist nicht eindeutig oder ungültig\.$/, 'Replacement for $1 is ambiguous or invalid.'],
    [/^Unbekannte, doppelte oder uneindeutige unvollständige Datumsangabe "([^"]+)" nicht zurückverschoben\.$/, 'Unknown, duplicate or ambiguous partial date "$1" was not restored.'],
    [/^Verschobene Datumsangabe "([^"]+)" fehlt im KI-Ergebnis\.$/, 'Shifted date "$1" is missing from the AI result.'],
    [/^Unbekanntes oder zusätzliches Datum "([^"]+)" nicht zurückverschoben\.$/, 'Unknown or additional date "$1" was not restored.'],
    [/^Datum "([^"]+)" kann nicht zurückverschoben werden\.$/, 'Date "$1" cannot be restored.'],
    [/^Verschobenes Datum (\S+) fehlt (\d+)-mal in der KI-Antwort\.$/, 'Shifted date $1 is missing $2 time(s) from the AI response.'],
    [/^Datum "([^"]+)": (.*)\.$/, 'Date "$1": $2.'],
  ];
  for(const [pattern,replacement] of patterns)if(pattern.test(text)){
    text=text.replace(pattern,replacement);
    break;
  }
  // Date-parser reasons are also emitted in German.
  for(const key of ['Zahlenformat Tag/Monat nicht eindeutig','Ungültiger Tag oder Monat']){
    text=text.replaceAll(key,translate(language,key));
  }
  return text;
}
