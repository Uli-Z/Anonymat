/** User-facing interface strings. Original text, tokens and detection rules are never translated. */
export type Language = 'de' | 'en';
export type LanguagePreference = Language | 'auto';
export const LANGUAGE_STORAGE_KEY = 'anonymat-ui-language-v1';

export function preferredBrowserLanguage(languages: readonly string[]): Language {
  for (const tag of languages) {
    const base=tag.trim().toLowerCase().split(/[-_]/,1)[0];
    if(base==='de'||base==='en')return base;
  }
  return 'en';
}
export function resolveLanguage(preference:LanguagePreference, languages:readonly string[]):Language {
  return preference==='auto'?preferredBrowserLanguage(languages):preference;
}
export function browserLanguages():readonly string[]{
  if(typeof navigator==='undefined')return ['en'];
  return navigator.languages?.length?[...navigator.languages]:[navigator.language || 'en'];
}
export function loadLanguagePreference():LanguagePreference{
  try {
    const stored=localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if(stored==='de'||stored==='en')return stored;
  } catch { /* Storage is optional; default to browser preference. */ }
  return 'auto';
}
export function saveLanguagePreference(preference:LanguagePreference):void{
  try {
    if(preference==='auto')localStorage.removeItem(LANGUAGE_STORAGE_KEY);
    else localStorage.setItem(LANGUAGE_STORAGE_KEY,preference);
  } catch { /* Continue to work without persistent storage. */ }
}
